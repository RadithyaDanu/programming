# membandngkan dua nilai, outputnya adalah boolean (True/False)
a = 10
b = 5
print(f"nilai a lebih besar dari b : {a > b}")  # True
print(f"nilai a lebih kecil dari b : {a < b}")  # False
print(f"nilai a lebih besar sama dengan b : {a >= b}")  # True
print(f"nilai a lebih kecil sama dengan b : {a <= b}")  # False
print(f"nilai a sama dengan b : {a == b}")  # False
print(f"nilai a tidak sama dengan b : {a != b}")  # True
# True
