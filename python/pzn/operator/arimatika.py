# operasi matematika pada variabel dan nilai
# tambah (+), kurang (-), kali (*), bagi (/)
# modulus/sisa pembagian (%), pangkat (**), floor division/pembagian bulat (//)
a = 10
b = 3
print(f"nilai a = {a}, nilai b = {b}")
# tambah
print(f"hasil a + b = {a + b}")
# kurang
print(f"hasil a - b = {a - b}")
# kali
print(f"hasil a * b = {a * b}")
# bagi
print(f"hasil a / b = {a / b}")
# modulus/sisa pembagian
print(f"hasil a % b = {a % b}")
# pangkat
print(f"hasil a ** b = {a ** b}")
# floor division/pembagian bulat
print(f"hasil a // b = {a // b}")
