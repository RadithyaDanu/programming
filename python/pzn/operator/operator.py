# operator merupakan simbol yhang digunakauntuk emlakan operasi pada variabel dan nilai
# py punya beberapa operator untuk memanipulasi data
# 1. aritmatika
# operator aritmatika digunakan untuk melakukan operasi matematika pada variabel dan nilai
# 2. assignment
# operator assignment digunakan untuk memberikan nilai ke variabel
# 3. perbandingan
# operator perbandingan digunakan untuk membandingkan dua nilai atau variabel
# 4. logika
# operator logika digunakan untuk menggabungkan beberapa kondisi logika, misalnya AND, OR, NOT
# 5. string
# operator string digunakan untuk menggabungkan string, misalnya + dan *
# prioritas operator
# urutan prioritas operator dari yang paling tinggi ke yang paling rendah adalah:
# 1. ** pangkat
# 2. *, /, //, % perkalian, pembagian, pembagian bulat, modulus
# 3. +, - penjumlahan, pengurangan
# 4. <, <=, >, >=, ==, != perbandingan
# 5. not
# 6. and
# 7. or
